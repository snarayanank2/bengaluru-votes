/**
 * Write a data migration that loads data/ward-issues.json into `ward_issues`.
 *
 *   npm run build:ward-issues -- <new_wards.geojson>            # refresh the JSON
 *   npm run migration:ward-issues -- drizzle/NNNN_xxx.sql       # write the migration SQL
 *
 * `deploy.sh` runs `npm run migrate` on every deploy, so a migration written this
 * way reaches production with no manual seed. The SQL (a) upserts each ward's
 * issues, (b) deletes catalog issues a ward no longer lists together with the
 * anonymous ballots that picked them, and (c) skips wards that are not in the
 * database yet, so a fresh database still migrates (`seed:wards` fills it later).
 *
 * Migrations are history: never edit one that has shipped. To change the issues
 * again, rebuild the JSON and write a NEW migration (add its journal entry in
 * drizzle/meta/_journal.json). Only the SQL is written.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SOURCE = path.join(__dirname, '..', 'data', 'ward-issues.json');
type Data = { issues: Array<{ key: string; titleEn: string; titleKn: string }>; wards: Record<string, string[]> };

const out = process.argv[2];
if (!out) {
  console.error('usage: npm run migration:ward-issues -- <drizzle/NNNN_name.sql>');
  process.exit(2);
}

const data = JSON.parse(readFileSync(SOURCE, 'utf8')) as Data;
const titles = new Map(data.issues.map((issue) => [issue.key, issue]));
const lit = (value: string) => `'${value.replace(/'/g, "''")}'`;
const ids = Object.keys(data.wards).sort((a, b) => Number(a) - Number(b));

const titleRows = data.issues.map((i) => `  (${lit(i.key)}, ${lit(i.titleEn)}, ${lit(i.titleKn)})`);
const wardRows: string[] = [];
for (const id of ids) {
  data.wards[id]!.forEach((key, index) => {
    if (!titles.has(key)) throw new Error(`ward ${id} references unknown issue ${key}`);
    wardRows.push(`(${id}, ${lit(key)}, ${index + 1})`);
  });
}
const chunks: string[] = [];
for (let i = 0; i < wardRows.length; i += 200) chunks.push(wardRows.slice(i, i + 200).join(', '));

const header = [
  `-- Ward-specific issues: ${ids.length} wards x ${data.wards[ids[0]!]!.length} issues, from data/ward-issues.json.`,
  `-- Generated by scripts/write-ward-issues-migration.ts; do not edit.`,
  `-- Wards missing from the database are skipped (seed:wards loads them later).`,
].join('\n');
const sql = header + '\n' + [
  `CREATE TEMP TABLE "_issue_titles" ("catalog_key" text PRIMARY KEY, "title_en" text NOT NULL, "title_kn" text NOT NULL);`,
  `INSERT INTO "_issue_titles" VALUES\n${titleRows.join(',\n')};`,
  `CREATE TEMP TABLE "_ward_issue_seed" ("ward_id" integer NOT NULL, "catalog_key" text NOT NULL, "position" integer NOT NULL);`,
  ...chunks.map((chunk) => `INSERT INTO "_ward_issue_seed" VALUES ${chunk};`),
  `DELETE FROM "anonymous_issue_vote_sets" WHERE "id" IN (
  SELECT s."set_id" FROM "anonymous_issue_vote_selections" s
  JOIN "ward_issues" wi ON wi."id" = s."ward_issue_id"
  WHERE wi."catalog_key" IS NOT NULL
    AND wi."ward_id" IN (SELECT DISTINCT "ward_id" FROM "_ward_issue_seed")
    AND NOT EXISTS (SELECT 1 FROM "_ward_issue_seed" n WHERE n."ward_id" = wi."ward_id" AND n."catalog_key" = wi."catalog_key")
);`,
  `DELETE FROM "ward_issues" wi WHERE wi."catalog_key" IS NOT NULL
  AND wi."ward_id" IN (SELECT DISTINCT "ward_id" FROM "_ward_issue_seed")
  AND NOT EXISTS (SELECT 1 FROM "_ward_issue_seed" n WHERE n."ward_id" = wi."ward_id" AND n."catalog_key" = wi."catalog_key");`,
  `INSERT INTO "ward_issues" ("ward_id", "catalog_key", "title_en", "title_kn", "authored_lang", "translation_status", "position")
SELECT n."ward_id", n."catalog_key", t."title_en", t."title_kn", 'en', 'done', n."position"
FROM "_ward_issue_seed" n
JOIN "_issue_titles" t ON t."catalog_key" = n."catalog_key"
JOIN "wards" w ON w."id" = n."ward_id"
ON CONFLICT ("ward_id", "catalog_key") WHERE "catalog_key" IS NOT NULL
DO UPDATE SET "title_en" = EXCLUDED."title_en", "title_kn" = EXCLUDED."title_kn", "translation_status" = 'done', "position" = EXCLUDED."position";`,
  `DROP TABLE "_ward_issue_seed";`,
  `DROP TABLE "_issue_titles";`,
].join('\n--> statement-breakpoint\n');

writeFileSync(path.resolve(out), `${sql}\n`);
console.log(`wrote ${path.resolve(out)} (${(sql.length / 1024).toFixed(0)} KB, ${wardRows.length} ward-issue rows)`);
